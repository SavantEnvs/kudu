#!/usr/bin/env bash
#
# mayhem/build.sh — build the Kudu fuzz harnesses and the KAT oracle probe.
#
# Kudu's own build (CMake + a ~30-package thirdparty tree fetched over the network) cannot run in this
# air-gapped image, so this compiles the self-contained Kudu sources the harnesses exercise (gutil strings,
# util coding/url/version/json/varint, the header-only RLE codec) straight from the checkout, against the
# Debian -dev packages the Dockerfile installs (glog, gflags, boost, rapidjson, protobuf, snappy, zlib).
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS SRC

cd "$SRC"
B="$SRC/build"
GEN="$B/gen"
mkdir -p "$GEN/kudu/util" "$B/obj-san" "$B/obj-plain"

# Normally generated by CMake's GenerateExportHeader.
cat > "$GEN/kudu/util/kudu_export.h" <<'H'
#ifndef KUDU_EXPORT_H
#define KUDU_EXPORT_H
#define KUDU_EXPORT __attribute__((visibility("default")))
#define KUDU_NO_EXPORT __attribute__((visibility("hidden")))
#define KUDU_DEPRECATED __attribute__((__deprecated__))
#define KUDU_DEPRECATED_EXPORT KUDU_EXPORT KUDU_DEPRECATED
#define KUDU_DEPRECATED_NO_EXPORT KUDU_NO_EXPORT KUDU_DEPRECATED
#endif
H

KUDU_SRCS="
  gutil/strings/numbers gutil/strings/escaping gutil/strings/stringpiece gutil/strings/util
  gutil/strings/split gutil/strings/strip gutil/strings/substitute gutil/strings/charset
  gutil/strings/ascii_ctype gutil/strings/memutil gutil/strings/join gutil/strings/strcat
  gutil/stringprintf gutil/strtoint gutil/int128 gutil/mathlimits
  gutil/hash/jenkins gutil/hash/city gutil/hash/hash
  util/hexdump util/malloc util/status util/slice util/faststring util/coding
  util/memcmpable_varint util/url-coding util/version_util util/jsonreader util/group_varint
"
DEFS="-DKUDU_HEADERS_NO_STUBS=1 -DKUDU_HEADERS_USE_SHORT_STATUS_MACROS=1"
INC="-I$SRC/src -I$GEN"
# alignment / pointer-overflow: benign patterns in gutil's hash and string code (see mayhem/KNOWN_FINDINGS.md).
SAN_CXX="$DEFS -std=c++17 $INC -O1 $SANITIZER_FLAGS -fsanitize=fuzzer-no-link $DEBUG_FLAGS -fno-sanitize=alignment,pointer-overflow"
PLAIN_CXX="$DEFS -std=c++17 $INC -O2 $COVERAGE_FLAGS"

build_objs() {  # <objdir> <cxx flags...>
  local dir="$1"; shift
  printf '%s\n' $KUDU_SRCS mayhem/stubs | xargs -P"$MAYHEM_JOBS" -I{} bash -c '
    set -e
    dir="$1"; shift
    s="{}"
    if [ "$s" = mayhem/stubs ]; then f="$SRC/mayhem/stubs.cc"; else f="$SRC/src/kudu/$s.cc"; fi
    "$CXX" "$@" -c "$f" -o "$dir/$(echo "$s" | tr / _).o"
  ' _ "$dir" "$@"
}

# 1) Sanitized + SanCov-instrumented Kudu objects (the fuzzed code itself).
build_objs "$B/obj-san" $SAN_CXX
"$CC" $SANITIZER_FLAGS -fsanitize=fuzzer-no-link $DEBUG_FLAGS -fno-sanitize=alignment,pointer-overflow -I"$SRC/src" \
  -c src/kudu/gutil/utf/rune.c -o "$B/obj-san/rune.o"
"$CXX" $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.cc -o "$B/lsan_off.o"

LIBS="-lglog -lgflags -lprotobuf -lsnappy -lz -lpthread"
"$CC" $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"

# 2) One fuzzer + one -standalone reproducer per harness.
HARNESSES="numbers escaping url_coding version json rle varint"
for h in $HARNESSES; do
  (
    "$CXX" $SAN_CXX -c "mayhem/harnesses/fuzz_$h.cc" -o "$B/fuzz_$h.o"
    "$CXX" $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/fuzz_$h.o" "$B"/obj-san/*.o "$B/lsan_off.o" $LIBS \
      -o "$SRC/fuzz_$h"
    "$CXX" $SANITIZER_FLAGS $DEBUG_FLAGS "$B/fuzz_$h.o" "$B/standalone_main.o" "$B"/obj-san/*.o "$B/lsan_off.o" $LIBS \
      -o "$SRC/fuzz_$h-standalone"
  ) &
done
wait
for h in $HARNESSES; do [ -x "$SRC/fuzz_$h" ] && [ -x "$SRC/fuzz_$h-standalone" ]; done

# 3) The oracle: a known-answer probe over the same sources, with NORMAL flags (no sanitizer, no -gdwarf-3).
build_objs "$B/obj-plain" $PLAIN_CXX
"$CC" -O2 -I"$SRC/src" -c src/kudu/gutil/utf/rune.c -o "$B/obj-plain/rune.o"
"$CXX" $PLAIN_CXX mayhem/kat/kat_probe.cc "$B"/obj-plain/*.o $LIBS -o "$SRC/kat_probe"
file "$SRC/kat_probe" | grep -q 'dynamically linked'
